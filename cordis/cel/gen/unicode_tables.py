#!/usr/bin/env python3
"""Writes cel/lib/unicode_tables.ml: the Unicode general categories, as
sorted code point ranges, for RE2's \\p{..} classes (cel/lib/re2.ml).

    python3 cel/gen/unicode_tables.py > cel/lib/unicode_tables.ml

From Python's unicodedata (its Unicode version is written into the file).
Unassigned code points (Cn) are left out, as RE2's tables leave them out;
surrogates (Cs) are kept, though no valid UTF-8 text holds one."""
import sys
import unicodedata

cats = {}
prev = None
for cp in range(0x110000):
    c = unicodedata.category(chr(cp))
    if c == "Cn":
        prev = None
        continue
    r = cats.setdefault(c, [])
    if prev == c and r and r[-1][1] == cp - 1:
        r[-1][1] = cp
    else:
        r.append([cp, cp])
    prev = c

out = sys.stdout
out.write("(* Generated by cel/gen/unicode_tables.py from Unicode %s: do not edit. The general\n" % unicodedata.unidata_version)
out.write("   categories, each as code point ranges [lo; hi; lo; hi; ...], sorted. *)\n\n")
out.write('let version = "%s"\n\n' % unicodedata.unidata_version)
out.write("let categories : (string * int array) list = [\n")
for c in sorted(cats):
    flat = []
    for lo, hi in cats[c]:
        flat += [lo, hi]
    body = ";".join("0x%x" % v for v in flat)
    out.write('  ("%s", [|%s|]);\n' % (c, body))
out.write("]\n")
