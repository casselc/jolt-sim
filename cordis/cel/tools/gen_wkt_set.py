#!/usr/bin/env python3
"""Regenerate lib/wkt_set.ml: the well-known types' FileDescriptorSet,
embedded so every registry has them (docs/cordis/rfc/0004-descriptor-
native-types.md, "Attaching descriptors"). Needs grpcio-tools."""
import os
import tempfile

import grpc_tools
from grpc_tools import protoc

inc = os.path.join(os.path.dirname(grpc_tools.__file__), "_proto")
files = ["any", "duration", "empty", "field_mask", "struct", "timestamp", "wrappers"]
with tempfile.TemporaryDirectory() as d:
    out = os.path.join(d, "wkt.binpb")
    rc = protoc.main(["protoc", f"-I{inc}", "--include_imports", f"--descriptor_set_out={out}"]
                     + [f"google/protobuf/{f}.proto" for f in files])
    assert rc == 0, rc
    data = open(out, "rb").read()
lit = "".join(f"\\x{b:02x}" for b in data)
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "lib", "wkt_set.ml"), "w") as f:
    f.write("(* Generated by cel/tools/gen_wkt_set.py: the well-known types'\n"
            "   FileDescriptorSet, from protobuf's own .proto files. Do not edit. *)\n\n")
    f.write(f'let data = "{lit}"\n')
print(len(data), "bytes")
